export const CURRICULUM_MANIFEST_BY_ID: Map<string, LessonManifestItem> = new Map(
  CURRICULUM_MANIFEST.map((item) => [item.id, item]),
);

export function getCurriculumLessonMetaById(id: string): LessonManifestItem | undefined {
  return CURRICULUM_MANIFEST_BY_ID.get(id);
}

export function getCurriculumManifestByLanguage(language: SupportedLanguage): LessonManifestItem[] {
  if (language !== 'en') return [];
  return CURRICULUM_MANIFEST;
}

export function getCurriculumManifestByLevel(level: string): LessonManifestItem[] {
  const normalized = level.toUpperCase();
  return CURRICULUM_MANIFEST.filter((item) => item.level.toUpperCase() === normalized);
}
