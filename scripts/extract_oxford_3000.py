def get_word_details(item):
    clean_w = item['clean'].lower()
    raw_word = item['word']
    pos = item['pos']
    lvl = item['level']

    front = f"{raw_word} ({pos})" if pos else raw_word

    if clean_w in existing_dict:
        match = existing_dict[clean_w]
        back = match.get('back', '')
        phonetic = match.get('phonetic', f"/{clean_w}/")
        example = match.get('example', f"Learning '{raw_word}' is essential for IELTS {lvl}.")
        return {
            'front': front,
            'back': back,
            'phonetic': phonetic,
            'example': example,
            'category': f"Oxford 3000 {lvl}"
        }

    if clean_w in CORE_FALLBACK_TRANSLATIONS:
        back = CORE_FALLBACK_TRANSLATIONS[clean_w]
    elif clean_w in trans_cache:
        back = trans_cache[clean_w]
    else:
        try:
            url = f"https://api.mymemory.translated.net/get?q={urllib.parse.quote(clean_w)}&langpair=en|uz"
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
            with urllib.request.urlopen(req, timeout=3) as resp:
                data = json.loads(resp.read().decode('utf-8'))
                res_text = data.get('responseData', {}).get('translatedText', '')
                if res_text and not res_text.startswith('MYMEMORY WARNING'):
                    back = res_text.lower()
                    trans_cache[clean_w] = back
                else:
                    back = f"{clean_w} ({pos})"
        except Exception:
            back = f"{clean_w} ({pos})"

    phonetic = f"/{clean_w}/"
    example = f"The word '{raw_word}' is frequently used in IELTS {lvl} communication."

    return {
        'front': front,
        'back': back,
        'phonetic': phonetic,
        'example': example,
        'category': f"Oxford 3000 {lvl}"
    }

# Process and save each level
for lvl in ['A1', 'A2', 'B1', 'B2']:
    items = levels_data[lvl]
    cards = []
    seen = set()

    for it in items:
        clean_w = it['clean'].lower()
        key = f"{clean_w}_{it['pos']}"
        if key in seen:
            continue
        seen.add(key)
        cards.append(get_word_details(it))

    out_file = f"src/data/decks/oxford_3000_{lvl.lower()}.json"
    with open(out_file, 'w', encoding='utf-8') as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)

    print(f"✅ Generated {out_file} with {len(cards)} cards.")

