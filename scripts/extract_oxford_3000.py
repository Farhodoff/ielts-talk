#!/usr/bin/env python3
import json
import os
import re
import urllib.parse
import urllib.request
import pypdf

# Load existing decks
with open('src/data/decks/starter.json', 'r', encoding='utf-8') as f:
    starter_data = json.load(f)

with open('src/data/decks/academic.json', 'r', encoding='utf-8') as f:
    academic_data = json.load(f)

existing_dict = {}
for item in starter_data + academic_data:
    front_clean = re.split(r'[\s(/,]', item['front'])[0].lower().strip()
    if front_clean and front_clean not in existing_dict:
        existing_dict[front_clean] = item

# Read PDF
reader = pypdf.PdfReader('American_Oxford_3000.pdf')
full_text = '\n'.join(p.extract_text() for p in reader.pages)
raw_lines = [l.strip() for l in full_text.split('\n') if l.strip()]

# Remove headers/footers
filtered = [
    l for l in raw_lines
    if not any(h in l for h in ['Oxford University Press', 'The Oxford 3000', 'most important words'])
]

# Merge wrapped lines
fixed_lines = []
buf = ''
for l in filtered:
    if buf:
        buf += ' ' + l
        if re.search(r'\b[A-C][1-2]\b', buf):
            fixed_lines.append(buf)
            buf = ''
    else:
        if not re.search(r'\b[A-C][1-2]\b', l):
            buf = l
        else:
            fixed_lines.append(l)
if buf:
    fixed_lines.append(buf)

print(f"Extracted {len(fixed_lines)} entries from PDF.")

# Parse into level groups
levels_data = {'A1': [], 'A2': [], 'B1': [], 'B2': []}

for line in fixed_lines:
    segments = re.findall(r'([a-zA-Z\s,./()]+?)\s*\b([A-C][1-2])\b', line)
    if not segments:
        continue

    first_seg_text = segments[0][0].strip()
    pos_match = re.search(r'\b(adj|adv|conj|det|n|prep|pron|v|modal|indefinite|definite|number|exclam)\b', first_seg_text)
    if pos_match:
        word = first_seg_text[:pos_match.start()].strip().rstrip(',').strip()
        first_pos = first_seg_text[pos_match.start():].strip()
    else:
        word = first_seg_text
        first_pos = ''

    clean_w = re.sub(r'[\d()]', '', word).strip()

    first_lvl = segments[0][1]
    if first_lvl in levels_data:
        levels_data[first_lvl].append({
            'word': word,
            'clean': clean_w,
            'pos': first_pos,
            'line': line,
            'level': first_lvl
        })

    for seg_pos, seg_lvl in segments[1:]:
        if seg_lvl in levels_data:
            levels_data[seg_lvl].append({
                'word': word,
                'clean': clean_w,
                'pos': seg_pos.strip(),
                'line': line,
                'level': seg_lvl
            })

# Translation helper cache
trans_cache_file = 'scripts/translation_cache.json'
if os.path.exists(trans_cache_file):
    with open(trans_cache_file, 'r', encoding='utf-8') as f:
        trans_cache = json.load(f)
else:
    trans_cache = {}

